import ipaddress
import itertools
import json
import re
import urllib.request
from collections import Counter
from dataclasses import dataclass, field, asdict
from datetime import datetime
from typing import Optional, List

import httpagentparser
import pandas as pd


def parse_user_agent(user_agent):
    user_agent = user_agent or ''
    agent = httpagentparser.detect(user_agent)
    browser = agent.get('browser', {}).get('name')
    os_name = agent.get('os', {}).get('name') or agent.get('platform', {}).get('name')

    # httpagentparser does not give the type of device, we deduce it from the User-Agent
    ua = user_agent.lower()
    if agent.get('bot') or any(word in ua for word in ('bot', 'crawler', 'spider')):
        device = 'bot'
    elif 'ipad' in ua or 'tablet' in ua or ('android' in ua and 'mobi' not in ua):
        device = 'tablet'
    elif 'mobi' in ua or 'iphone' in ua:
        device = 'mobile'
    else:
        device = 'desktop'
    return browser, os_name, device


def query_terms(query):
    # original words of the user (lowercase), not the preprocessed terms of the index
    return re.findall(r'[a-z0-9]+', query.lower())


# stemmed gender words: they appear in most queries and do not tell the goal of the user,
# so they are not used to decide if two queries belong to the same mission
GENERIC_TERMS = {'men', 'man', 'women', 'woman', 'boy', 'girl', 'kid', 'unisex'}

_location_cache = {}


def get_location(ip):
    # ip-api.com instead of an offline database: simpler and nothing to download,
    # but the IP is sent to a third party (explained in the report)
    try:
        if not ip or not ipaddress.ip_address(ip).is_global:
            return None, None
    except ValueError:
        return None, None
    if ip not in _location_cache:
        try:
            url = f'http://ip-api.com/json/{ip}?fields=status,country,city'
            with urllib.request.urlopen(url, timeout=2) as response:
                data = json.load(response)
        except Exception:
            # no internet or service down: the web keeps working without location
            return None, None
        if data.get('status') == 'success':
            _location_cache[ip] = (data.get('country'), data.get('city'))
        else:
            _location_cache[ip] = (None, None)
    return _location_cache[ip]


# star schema: Session and Document (the corpus of web_app.py) are dimensions,
# Request, Query and Click are facts. There is no Time table: date, hour and weekday
# are derived from the timestamp of each fact.

@dataclass
class Session:
    session_id: str
    visitor_id: str                  # persistent cookie to follow the same browser across sessions
    start_time: datetime
    last_seen: datetime              # used to close the session after inactivity
    ip: Optional[str] = None
    user_agent: Optional[str] = None
    browser: Optional[str] = None
    os: Optional[str] = None
    device: Optional[str] = None
    country: Optional[str] = None
    city: Optional[str] = None
    simulated: bool = False          # generated by simulation.py, not a real visit


@dataclass
class Request:
    request_id: int
    session_id: Optional[str]
    timestamp: datetime
    method: str
    path: str
    status_code: Optional[int] = None
    response_ms: Optional[float] = None
    referrer: Optional[str] = None


@dataclass
class Query:
    search_id: int
    session_id: Optional[str]
    timestamp: datetime
    query: str
    terms: List[str] = field(default_factory=list)
    num_terms: int = 0
    processed_terms: List[str] = field(default_factory=list)
    method: Optional[str] = None
    only_available: bool = False
    results_found: Optional[int] = None
    match_mode: Optional[str] = None
    order_in_session: Optional[int] = None
    mission_id: Optional[int] = None


@dataclass
class Click:
    click_id: int
    session_id: Optional[str]         # redundant (also reachable through search_id), kept to filter faster
    search_id: Optional[int]
    pid: str
    rank: Optional[int]
    timestamp: datetime
    click_type: str = 'details'       # 'details' (our page) or 'external' (original website)
    dwell_time_s: Optional[float] = None


class AnalyticsData:

    def __init__(self):
        self.sessions = {}
        self.requests = []
        self.queries = []
        self.clicks = []

        self._request_ids = itertools.count(1)
        self._search_ids = itertools.count(1)
        self._click_ids = itertools.count(1)
        self._mission_ids = itertools.count(1)

    def save_session(self, session_id, visitor_id, ip=None, user_agent=None, browser=None, os=None,
                     device=None, country=None, city=None, timestamp=None, simulated=False):
        timestamp = timestamp or datetime.now()
        row = Session(session_id=session_id, visitor_id=visitor_id, start_time=timestamp, last_seen=timestamp,
                      ip=ip, user_agent=user_agent, browser=browser, os=os, device=device,
                      country=country, city=city, simulated=simulated)
        self.sessions[session_id] = row
        return row

    def save_request(self, session_id, method, path, status_code=None, response_ms=None, referrer=None,
                     timestamp=None):
        timestamp = timestamp or datetime.now()
        row = Request(request_id=next(self._request_ids), session_id=session_id, timestamp=timestamp,
                      method=method, path=path, status_code=status_code, response_ms=response_ms,
                      referrer=referrer)
        self.requests.append(row)
        if session_id in self.sessions:
            self.sessions[session_id].last_seen = timestamp
        return row

    def save_query(self, session_id, query, terms, processed_terms=(), method=None, only_available=False,
                   results_found=None, match_mode=None, timestamp=None):
        timestamp = timestamp or datetime.now()
        order = 1 + sum(1 for q in self.queries if q.session_id == session_id) if session_id else None
        row = Query(search_id=next(self._search_ids), session_id=session_id, timestamp=timestamp,
                    query=query, terms=list(terms), num_terms=len(terms), processed_terms=list(processed_terms),
                    method=method, only_available=only_available, results_found=results_found,
                    match_mode=match_mode, order_in_session=order,
                    mission_id=self.assign_mission(session_id, processed_terms))
        self.queries.append(row)
        return row.search_id

    def assign_mission(self, session_id, processed_terms):
        # missions are computed per visitor (not per session), so a mission whose queries are in
        # several physical sessions is a research mission. A query joins the most recent mission
        # of the same visitor with which it shares a meaningful term, otherwise it starts a new one
        current = self.sessions.get(session_id)
        meaningful = set(processed_terms) - GENERIC_TERMS
        if current and meaningful:
            for q in reversed(self.queries):
                previous = self.sessions.get(q.session_id)
                if (previous and previous.visitor_id == current.visitor_id
                        and meaningful & (set(q.processed_terms) - GENERIC_TERMS)):
                    return q.mission_id
        return next(self._mission_ids)

    def set_query_results(self, search_id, results_found, match_mode):
        # the search_id is needed before searching (it goes in the result links),
        # the number of results is only known after searching
        query = self.get_query(search_id)
        if query:
            query.results_found = results_found
            query.match_mode = match_mode

    def save_click(self, session_id, search_id, pid, rank, click_type='details', timestamp=None):
        timestamp = timestamp or datetime.now()
        row = Click(click_id=next(self._click_ids), session_id=session_id, search_id=search_id, pid=pid,
                    rank=rank, timestamp=timestamp, click_type=click_type)
        self.clicks.append(row)
        return row.click_id

    def set_dwell_time(self, click_id, seconds):
        for click in self.clicks:
            if click.click_id == click_id:
                click.dwell_time_s = seconds
                return

    def get_query(self, search_id):
        for q in self.queries:
            if q.search_id == search_id:
                return q
        return None

    def get_click(self, click_id):
        for c in self.clicks:
            if c.click_id == click_id:
                return c
        return None

    def clicks_per_document(self):
        return Counter(c.pid for c in self.clicks if c.click_type == 'details')

    def to_dataframes(self):
        return {
            'sessions': pd.DataFrame([asdict(s) for s in self.sessions.values()]),
            'requests': pd.DataFrame([asdict(r) for r in self.requests]),
            'queries': pd.DataFrame([asdict(q) for q in self.queries]),
            'clicks': pd.DataFrame([asdict(c) for c in self.clicks]),
        }

    def to_dict(self):
        return {
            'sessions': [asdict(s) for s in self.sessions.values()],
            'requests': [asdict(r) for r in self.requests],
            'queries': [asdict(q) for q in self.queries],
            'clicks': [asdict(c) for c in self.clicks],
        }

    def export_json(self, path):
        # data is kept in memory, this allows saving it before stopping the server
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(self.to_dict(), f, indent=2, default=str)
